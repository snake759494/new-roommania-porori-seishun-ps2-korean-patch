def wipe(img, box, bg):
    """상자 안 글자만 지움: 흰 바탕이면 어두운 픽셀 중 패널 테두리(긴 직선)는 남기고 흰색으로"""
    from scipy import ndimage
    a = np.array(img); x0, y0, x1, y1 = box
    sub = a[y0:y1, x0:x1]; g = sub[..., :3].astype(int).mean(2)
    if bg == 'i':      # 회색 그러데이션 말풍선: 진한 획만 주변으로 메움
        import cv2
        m = (g < 110).astype(np.uint8) * 255
        m = cv2.dilate(m, np.ones((3, 3), np.uint8), iterations=2)
        bgr = cv2.cvtColor(sub[..., :3].astype(np.uint8), cv2.COLOR_RGB2BGR)
        sub[..., :3] = cv2.cvtColor(cv2.inpaint(bgr, m, 7, cv2.INPAINT_TELEA), cv2.COLOR_BGR2RGB)
    elif bg == 'w':
        ink = g < 170
        lab, n = ndimage.label(ink)
        keep = np.zeros_like(ink)
        for k, sl in enumerate(ndimage.find_objects(lab), 1):
            hh = sl[0].stop - sl[0].start; ww = sl[1].stop - sl[1].start
            if hh > 60 and ww < 6 or ww > 60 and hh < 6: keep |= lab == k   # 테두리 직선
        m = ndimage.binary_dilation(ink & ~keep, iterations=1)
        sub[m] = (255, 255, 255, 255)
    elif bg == 'k':
        sub[..., :3] = 0; sub[..., 3] = 255
    else:   # 'k' 검정 상자, 'n' 어두운 그림 위 흰 글자: 밝은 획을 주변으로 메움
        import cv2
        m = ndimage.binary_dilation(g > 170, iterations=1).astype(np.uint8) * 255
        bgr = cv2.cvtColor(sub[..., :3].astype(np.uint8), cv2.COLOR_RGB2BGR)
        sub[..., :3] = cv2.cvtColor(cv2.inpaint(bgr, m, 7, cv2.INPAINT_TELEA), cv2.COLOR_BGR2RGB)
    a[y0:y1, x0:x1] = sub
    return Image.fromarray(a)


def render_page(img, caps):
    for x0, y0, x1, y1, bg, text, size, d in caps + SFX.get(id(caps), []):
        if bg == 's':   # 그림 속 효과음 풀이: 검은 글자 + 흰 외곽선(원래 그림은 그대로)
            img = put(img, text, (x0, y0, x1, y1), w='H', size=size, color=K_, vertical=(d == 'v'), stroke=2, stroke_color=W_)
            continue
        img = wipe(img, (x0, y0, x1, y1), bg)
        img = put(img, text, (x0 + 2, y0 + 2, x1 - 2, y1 - 2), w='SB', size=size, color=W_ if bg in 'kn' else K_,
                  vertical=(d == 'v'), line_gap=3, stroke=2 if bg == 'n' else 0, stroke_color=K_)
    return img


